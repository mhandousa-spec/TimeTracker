Future<void> showCreateServiceDialog(
    BuildContext context,
    ServicesHistoryModel? modelCreate,
    Map<String, Map<int, bool>> mapModel,
    bool switchOne,
    bool switchTwo,
    ) async {
  final stableNavCtx = context;

  // ✅ IMPROVED: Better edit mode detection
  bool isCreatingNew = false;
  bool isDraft = false;
  bool isEditingExisting = false;

  if (modelCreate != null) {
    final docId = modelCreate.currentId;
    final state = modelCreate.currentState;

    // Check if it's a SharedPrefs draft (starts with 'draft_')
    if (docId.startsWith('draft_')) {
      isDraft = true;
    }
    // ✅ FIX: Correct edit detection - check for active/submitted state AND real ID
    else if (docId.isNotEmpty &&
        !docId.startsWith('draft_') &&
        !docId.startsWith('User') &&
        (state == 'active' || state == 'submitted' || state == 'inactive')) {
      isEditingExisting = true;
    }
    // OR if it has a real Firebase ID format (not generated by our app)
    else if (docId.isNotEmpty &&
        !docId.startsWith('draft_') &&
        modelCreate.currentDurationOfServices.isNotEmpty &&
        modelCreate.currentDurationOfServices != "-") {
      isEditingExisting = true;
    }
    // Otherwise it's creating new
    else {
      isCreatingNew = true;
    }
  } else {
    // No model at all = creating new
    isCreatingNew = true;
  }

  return showDialog(
    context: stableNavCtx,
    barrierDismissible: true,
    builder: (dlgCtx) {
      final lightMode = Theme.of(context).brightness == Brightness.light;

      // Get screen dimensions
      final screenWidth = MediaQuery.of(dlgCtx).size.width;
      final screenHeight = MediaQuery.of(dlgCtx).size.height;
      final orientation = MediaQuery.of(dlgCtx).orientation;

      // Determine platform type
      final isMobile = screenWidth < 600;
      final isTablet = screenWidth >= 600 && screenWidth < 1200;
      final isDesktop = screenWidth >= 1200;
      final isPortrait = orientation == Orientation.portrait;

      // Calculate responsive dimensions
      double dialogWidth;
      double dialogHeight;
      double lottieSize;
      double titleFontSize;
      double messageFontSize;
      double buttonWidth;
      double buttonHeight;

      if (isMobile) {
        dialogWidth = screenWidth * 0.85;
        dialogHeight = isPortrait
            ? screenHeight * 0.35
            : screenHeight * 0.55;
        lottieSize = 60.0;
        titleFontSize = 18.0;
        messageFontSize = 14.0;
        buttonWidth = (dialogWidth - 80) * 0.4;
        buttonHeight = 36.0;
      } else if (isTablet) {
        if (isPortrait) {
          dialogWidth = screenWidth * 0.7;
          dialogHeight = screenHeight * 0.3;
        } else {
          dialogWidth = screenWidth * 0.5;
          dialogHeight = screenHeight * 0.45;
        }
        lottieSize = 70.0;
        titleFontSize = 20.0;
        messageFontSize = 15.0;
        buttonWidth = 135.0;
        buttonHeight = 38.0;
      } else {
        dialogWidth = 450.0;
        dialogHeight = 280.0;
        lottieSize = 80.0;
        titleFontSize = 22.0;
        messageFontSize = 16.0;
        buttonWidth = 140.0;
        buttonHeight = 40.0;
      }

      dialogWidth = dialogWidth.clamp(300.0, 600.0);
      dialogHeight = dialogHeight.clamp(200.0, 400.0);

      return ScaleInContent(child: Dialog(
        backgroundColor: Theme.of(dlgCtx).brightness == Brightness.light
            ? AppColors.white
            : AppColors.chatBackground,
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(8.0),
        ),
        child: Container(
          width: 500.w,
      //    height: dialogHeight,
          padding: EdgeInsets.all(isMobile ? 12.0 : 15.0),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            mainAxisAlignment: MainAxisAlignment.spaceEvenly,
            children: [
              // Lottie Animation
              Flexible(
                flex: 2,
                child: Lottie.asset(
                  isEditingExisting
                      ? "assets/lottie_assets/main_lottie_assets/lottie_confirmation.json"
                      : isDraft
                      ? "assets/lottie_assets/main_lottie_assets/lottie_Edit Document.json"
                      : "assets/lottie_assets/main_lottie_assets/lottie_Edit Document.json",
                  width: lottieSize,
                  height: lottieSize,
                  fit: BoxFit.contain,
                  repeat: true,
                  animate: true,
                ),
              ),

              SizedBox(height: isMobile ? 10.0 : 15.0),

              // Title
              Flexible(
                flex: 1,
                child: Text(
                  isEditingExisting
                      ? S.of(dlgCtx).editingService
                      : isDraft
                      ? S.of(dlgCtx).draftService
                      : S.of(dlgCtx).creatingService,
                  style: StyleText.fontSize20Weight500.copyWith(
                    color: lightMode ? AppColors.blackButton : AppColors.white,
                  ),
                  textAlign: TextAlign.center,
                ),
              ),

              SizedBox(height: isMobile ? 8.0 : 12.0),

              // Message
              Flexible(
                flex: 2,
                child: Text(
                  isEditingExisting
                      ? S.of(dlgCtx).areYouSureEditService
                      : isDraft
                      ? S.of(dlgCtx).areYouSureYouWantToSaveAsDraft
                      : S.of(dlgCtx).areYouSureCreateService,
                  textAlign: TextAlign.center,
                  style: StyleText.fontSize14Weight400.copyWith(
                    fontSize: messageFontSize,
                    fontWeight: FontWeight.w500,
                    color: Theme.of(dlgCtx).brightness == Brightness.light
                        ? AppColors.secondaryText
                        : AppColors.grey,
                  ),
                ),
              ),

              SizedBox(height: isMobile ? 12.0 : 15.0),

              // Buttons
              Flexible(
                flex: 1,
                child: Padding(
                  padding: EdgeInsets.symmetric(
                      horizontal: isMobile ? 20.0 : 56.0),
                  child: Row(
                    mainAxisAlignment: MainAxisAlignment.spaceEvenly,
                    children: [
                      // No Button
                      Flexible(
                        child: customButton(
                          title: S.of(dlgCtx).no,
                          function: () {
                            Navigator.of(stableNavCtx, rootNavigator: true).pop();
                          },
                          textStyle: StyleText.fontSize14Weight400.copyWith(
                            fontSize: messageFontSize,
                            color: AppColors.onSecondaryAction,
                            fontWeight: FontWeight.w500,
                          ),
                          width: buttonWidth,
                          height: buttonHeight,
                          radius: 4.0,
                          color: AppColors.secondaryAction,
                        ),
                      ),

                      SizedBox(width: isMobile ? 10.0 : 20.0),

                      // Yes/Update Button
                      Flexible(
                        child: customButton(
                          title: S.of(dlgCtx).yes,
                          function: () async {
                            // 022: no try/catch in widget callbacks (§11.2) — the
                            // cubit emits error states for save/update failures.
                            final prefs = await SharedPreferences.getInstance();

                              // ✅ CRITICAL FIX: Load all data with fallback to modelCreate
                              // This prevents data loss during edit when user doesn't visit all screens

                              final servicesProviderNameEnglish =
                                  await SharedPrefsHelper.getString("service_name_en")
                                      ?? modelCreate?.currentServiceNameEnglish
                                      ?? '';

                              final servicesProviderNameArabic =
                                  await SharedPrefsHelper.getString("service_name_ar")
                                      ?? modelCreate?.currentServiceNameArabic
                                      ?? '';

                              final servicesDescriptionEnglish =
                                  await SharedPrefsHelper.getString("service_description_en")
                                      ?? modelCreate?.currentServiceDescriptionEnglish
                                      ?? '';

                              final servicesDescriptionArabic =
                                  await SharedPrefsHelper.getString("service_description_ar")
                                      ?? modelCreate?.currentServiceDescriptionArabic
                                      ?? '';

                              final selectedDuration =
                                  await SharedPrefsHelper.getString("duration_value")
                                      ?? modelCreate?.currentDurationOfServices
                                      ?? '';

                              final selectedDurationUnit =
                                  await SharedPrefsHelper.getString("duration_unit")
                                      ?? modelCreate?.currentSelectedDurationUnit
                                      ?? '';

                              // ✅ FIX 30/8/2026 — THE UPLOADED IMAGE NEVER
                              // REACHED THE CREATED SERVICE.
                              //
                              // This dialog is the final write of the whole
                              // create-service wizard, and it read every page-1
                              // field back except this one. The
                              // `ServicesHistoryModel.createNew` call below
                              // simply did not pass `imageUrl`, so it took the
                              // parameter's default of '' and the document went
                              // to Firestore with no `Image_Url` — which is why
                              // `ServiceGridCard` drew the headset placeholder
                              // for a service that definitely had a picture.
                              //
                              // Read with the same `??` shape as its siblings:
                              // it falls back to the stored model only when the
                              // key is ABSENT, so a user who deletes the image
                              // stages '' and the deleted picture does not come
                              // back (its Storage object is gone by then, so
                              // restoring the URL would render a broken image).
                              final serviceImageUrl =
                                  await SharedPrefsHelper.getString('service_image_url')
                                      ?? modelCreate?.currentImageUrl
                                      ?? '';

                              // ✅ CRITICAL: Lists with fallback to preserve existing data
                              final selectedProvidedEmployees =
                                  await SharedPrefsEmployeeHelper.getSelectedEmployees()
                                      ?? modelCreate?.currentProviderServices
                                      ?? [];

                              final selectedDepartment =
                                  await SharedPrefsDepartmentsHelper.getDepartments()
                                      ?? modelCreate?.currentSelectDepartment
                                      ?? [];

                              final selectedApprovedEmployees =
                                  await SharedPrefsApprovalHelper.getApprovalCycle()
                                      ?? modelCreate?.currentApprovalCycle
                                      ?? [];

                              final slaOne = await SharedPrefsHelper.getString('sla_one')
                                  ?? modelCreate?.currentSlaOneControllerEnglish
                                  ?? '';

                              final slaTwo = await SharedPrefsHelper.getString('sla_two')
                                  ?? modelCreate?.currentSlaTwoControllerEnglish
                                  ?? '';

                              final notifyRequesterChecked =
                                  await SharedPrefsHelper.getBool('Notify Service Requester_checked')
                                      ?? modelCreate?.currentNotifyRequesterChecked
                                      ?? false;

                              final notifyProviderChecked =
                                  await SharedPrefsHelper.getBool('Notify Service Provider_checked')
                                      ?? modelCreate?.currentNotifyProviderChecked
                                      ?? false;

                              final notifyManagerChecked =
                                  await SharedPrefsHelper.getBool('Notify Provider Manager_checked')
                                      ?? modelCreate?.currentNotifyManagerChecked
                                      ?? false;

                              final notifyProviderSwitches =
                                  mapModel[S.of(dlgCtx).notifyServiceProvider] ?? {};
                              switchOne = notifyProviderSwitches[0] ?? false;

                              final notifyManagerSwitches =
                                  mapModel[S.of(dlgCtx).notifyProviderManager] ?? {};
                              switchTwo = notifyManagerSwitches[0] ?? false;

                              // ✅ DEBUG: Print loaded data

                              // ✅ FIX: Proper ID generation logic
                              String docId;
                              if (isEditingExisting && modelCreate?.currentId.isNotEmpty == true) {
                                // Use existing document ID for edit
                                docId = modelCreate!.currentId;
                              } else if (isDraft && modelCreate?.currentId.isNotEmpty == true) {
                                // For drafts, check if it's a temp ID or real ID
                                if (modelCreate!.currentId.startsWith('draft_') ||
                                    modelCreate.currentId.startsWith('User')) {
                                  // It's a temp ID, generate new one
                                  final now = Timestamp.now();
                                  final formattedDate = DateFormat("MMMdd_yyyy").format(now.toDate());
                                  final randomId = Random().nextInt(100000);
                                  docId = "User$randomId$formattedDate";
                                } else {
                                  // It's a real ID, use it
                                  docId = modelCreate.currentId;
                                }
                              } else {
                                // Creating completely new service
                                final now = Timestamp.now();
                                final formattedDate = DateFormat("MMMdd_yyyy").format(now.toDate());
                                final randomId = Random().nextInt(100000);
                                docId = "User$randomId$formattedDate";
                              }

                              final bool notifyRequesterSwitch0FromMap =
                                  mapModel[S.of(dlgCtx).notifyServiceProvider]?[0] ?? false;
                              final bool notifyManagerSwitch1FromMap =
                                  mapModel[S.of(dlgCtx).notifyProviderManager]?[0] ?? false;

                              final limitAvailabilityFlag =
                                  await SharedPrefsHelper.getBool('limitAvailability') ??
                                      (modelCreate?.currentLimitAvailability ?? false);
                              final requireApprovalFlag =
                                  await SharedPrefsHelper.getBool('requireApproval') ??
                                      (modelCreate?.currentRequireApproval ?? false);

                              final selectedDepartmentFinal =
                              limitAvailabilityFlag ? (selectedDepartment.isNotEmpty ? selectedDepartment : []) : [];
                              final List<EmployeeEntityModell> selectedApprovedEmployeesFinal =
                              requireApprovalFlag ? (selectedApprovedEmployees.isNotEmpty ? selectedApprovedEmployees : []) : [];

                              // Create ServicesHistoryModel
                              final model = ServicesHistoryModel.createNew(
                                id: docId,
                                state: isEditingExisting ? (modelCreate!.currentState) : 'active',
                                // ✅ FIX (draft bug #1): `== true` treated a
                                // MISSING pref as "inactive". Completing a
                                // draft never went through the status toggle,
                                // so the pref was absent (or left at the
                                // draft's bogus 'draft' status) and every
                                // finished draft came out INACTIVE. Absent now
                                // means active, matching the form default and
                                // SlaNotificationCubit.updateAndSaveModel.
                                status: (await SharedPrefsHelper.getBool('service_status') ?? true)
                                    ? "active"
                                    : "inactive",
                                serviceNameEnglish: servicesProviderNameEnglish,
                                serviceNameArabic: servicesProviderNameArabic,
                                serviceDescriptionEnglish: servicesDescriptionEnglish,
                                serviceDescriptionArabic: servicesDescriptionArabic,
                                durationOfServices: selectedDuration,
                                selectedDurationUnit: selectedDurationUnit,
                                imageUrl: serviceImageUrl,
                                providerServices: selectedProvidedEmployees,
                                selectDepartment: selectedDepartmentFinal,
                                approvalCycle: selectedApprovedEmployeesFinal,
                                limitAvailability: limitAvailabilityFlag,
                                requireApproval: requireApprovalFlag,
                                slaOneControllerEnglish: slaOne,
                                slaTwoControllerEnglish: slaTwo,
                                notifyRequesterChecked: notifyRequesterChecked,
                                notifyProviderChecked: notifyProviderChecked,
                                notifyManagerChecked: notifyManagerChecked,
                                notifyRequesterSwitch0: notifyRequesterSwitch0FromMap,
                                notifyManagerSwitch1: notifyManagerSwitch1FromMap,
                                emailRequester: prefs.getString("emailRequester") ?? '',
                              );

                              // ✅ FIX: Use correct service method based on mode
                              // B3 FIX: removed the unawaited duplicate
                              // `saveRequestService(docId, model)` that raced the
                              // awaited save/update below (double write).
                              final bool ok = isEditingExisting
                                  ? await ServicesManagerCubit.get(stableNavCtx).updateService(docId, model)
                                  : await ServicesManagerCubit.get(stableNavCtx).saveService(docId, model);

                              if (!ok) {
                                // B3 FIX: the remote write failed — do NOT delete
                                // the local draft or show success. Close loading
                                // and surface the error so nothing is lost.
                                if (Navigator.of(stableNavCtx, rootNavigator: true).canPop()) {
                                  Navigator.of(stableNavCtx, rootNavigator: true).pop();
                                }
                                await showDialog(
                                  context: stableNavCtx,
                                  builder: (dctx) => AlertDialog(
                                    title: Text(S.of(dctx).error),
                                    content: Text(S.of(dctx).errorOccurred),
                                    actions: [
                                      TextButton(
                                        onPressed: () => Navigator.of(dctx).pop(),
                                        child: Text(S.of(dctx).ok),
                                      ),
                                    ],
                                  ),
                                );
                                return;
                              }

                              await SharedPrefsHelper.setString('service_image_url', '');

                              // ✅ FIX (draft bug #2): the service is now live
                              // under a brand new document, but the original
                              // `draft_…` document was left behind with
                              // state/status ['draft'] — so the home page kept
                              // listing it under Drafts alongside the live
                              // service. Remove every draft document that fed
                              // this service, both the one attached to the
                              // model and the one tracked by the wizard
                              // session (they can differ when the user saved
                              // "for later" on an earlier step).
                              final draftCubit = ServicesManagerCubit.get(stableNavCtx);
                              final trackedDraftId = draftCubit.currentDraftId ?? '';
                              final modelDraftId = modelCreate?.currentId ?? '';

                              final draftIdsToDiscard = <String>{
                                if (modelDraftId.startsWith('draft_')) modelDraftId,
                                if (trackedDraftId.startsWith('draft_')) trackedDraftId,
                              };

                              for (final staleDraftId in draftIdsToDiscard) {
                                await draftCubit.discardPublishedDraft(staleDraftId);
                                // Clear the local (SharedPrefs) copy too.
                                await SharedPrefsServiceMaster.removeDraftById(staleDraftId);
                              }

                              draftCubit.clearCurrentDraft();

                              // Reset the status pref only after the draft
                              // cleanup, so nothing above reads a stale value.
                              await SharedPrefsHelper.setBool('service_status', true);

                              // Clear temp data for new services
                              if (!isEditingExisting) {
                                await SharedPrefsHelper.setString('sla_one', '');
                                await SharedPrefsHelper.setString('sla_two', '');
                                await SharedPrefsHelper.setString('service_name_en', '');
                                await SharedPrefsHelper.setString('service_name_ar', '');
                                await SharedPrefsHelper.setString('service_description_en', '');
                                await SharedPrefsHelper.setString('service_description_ar', '');
                                await SharedPrefsHelper.setString('duration_value', '');
                                await SharedPrefsHelper.setString('duration_unit', '');
                              }

                              final cubit = ServicesManagerCubit.get(stableNavCtx);
                              cubit.docService = null;

                              ServicesManagerCubit.get(stableNavCtx).getAllServices();

                              Navigator.of(stableNavCtx, rootNavigator: true).pop();
                              correctShowDialog(stableNavCtx, model, isEditingExisting);
                          },
                          textStyle: StyleText.fontSize14Weight400.copyWith(
                              fontSize: messageFontSize,
                              fontWeight: FontWeight.w500,
                              color: AppColors.textButton),
                          width: buttonWidth,
                          height: buttonHeight,
                          radius: 4.0,
                          color: AppColors.primary,
                        ),
                      ),
                    ],
                  ),
                ),
              ),

              SizedBox(height: isMobile ? 4.0 : 4.0),
            ],
          ),
        ),
      ));
    },
  );
}

Future<void> correctShowDialog(
    BuildContext context,
    ServicesHistoryModel model,
    [bool isEditing = false]
    ) async

{
  final stableNavCtx = context;
  bool navigated = false;

  // ✅ Only clear selection when creating new service, not editing
  if (!isEditing) {
    await _clearSelectionAfterServiceCreation(stableNavCtx);
  }

  await showDialog(
    context: stableNavCtx,
    barrierDismissible: true,
    builder: (dialogCtx) {

      final isArabic = Localizations.localeOf(context).languageCode == 'ar';
      // Auto-close and navigate after 2 seconds
      Future.delayed(const Duration(seconds: 2), () {
        if (!navigated) {
          navigated = true;
          Navigator.of(stableNavCtx, rootNavigator: true).pop();
          navigateAndFinish(stableNavCtx, LayoutScreenServices());
        }
      });

      return WillPopScope(
        onWillPop: () async {
          if (!navigated) {
            navigated = true;
            Navigator.of(stableNavCtx, rootNavigator: true).pop();
            navigateAndFinish(stableNavCtx, LayoutScreenServices());
          }
          return false;
        },
        child: GestureDetector(
          behavior: HitTestBehavior.opaque,
          onTap: () {
            if (!navigated) {
              navigated = true;
              Navigator.of(stableNavCtx, rootNavigator: true).pop();
              navigateAndFinish(stableNavCtx, LayoutScreenServices());
            }
          },
          child: Dialog(
            backgroundColor: Theme.of(dialogCtx).brightness == Brightness.light
                ? AppColors.white
                : AppColors.chatBackground,
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(8.r),
            ),
            child: Container(
              width: 500.w, // ✅ Fixed width using ScreenUtil
              padding: EdgeInsets.all(24.r), // ✅ Responsive padding
              child: Column(
                mainAxisSize: MainAxisSize.min, // ✅ This makes height dynamic
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  // Success Animation
                  Lottie.asset(
                    'assets/lottie_assets/main_lottie_assets/lottie_approved.json',
                    width: 70.sp,
                    height: 70.sp,
                    fit: BoxFit.contain,
                    repeat: true,
                  ),

                  // space
                  SizedBox(height: 25.h),

                  // Title - Different for Edit vs Create
                  Text(
                    isEditing
                        ? S.of(context).servicesUpdated
                        : S.of(dialogCtx).createService,
                    textAlign: TextAlign.center,
                    style: StyleText.fontSize20Weight500.copyWith(
                      color: Theme.of(dialogCtx).brightness == Brightness.light
                          ? AppColors.blackButton
                          : AppColors.white,
                    ),
                  ),

                  // space
                  SizedBox(height: 18.h),

                  // Message - Different for Edit vs Create
                  Text(
                    isEditing
                        ? S.of(context).sm_serviceUpdatedSuccessfully

                        : S.of(context).sm_serviceCreatedSuccessfully,

                    textAlign: TextAlign.center,
                    style: StyleText.fontSize15Weight400.copyWith(
                      color: Theme.of(dialogCtx).brightness == Brightness.light
                          ? AppColors.secondaryText
                          : AppColors.grey,
                    ),
                  ),
                ],
              ),
            ),
          ),
        ),
      );
    },
  );
}

Future<void> _clearSelectionAfterServiceCreation(BuildContext context) async {
  // 022: no try/catch in the UI (§11.2).
  await SharedPrefsEmployeeHelper.clearSelectedEmployees();
  await SharedPrefsHelper.setString('current_draft_id', '');
  await SharedPrefsHelper.setString('current_service_docId', '');

  final cubit = ServicesManagerCubit.get(context);
  cubit.docService = null;
}

