class AppCountryFlag extends StatelessWidget {
  const AppCountryFlag({
    super.key,
    required this.isoCode,
    this.width = 24,
    this.height = 18,
    this.borderRadius = 2,
  });

  /// ISO 3166-1 alpha-2 country code, any case ("EG", "eg").
  final String isoCode;

  /// Already-scaled logical sizes.
  final double width;
  final double height;
  final double borderRadius;

  @override
  Widget build(BuildContext context) {
    final String code = isoCode.trim().toLowerCase();
    if (!kBundledFlagCodes.contains(code)) {
      // No flag for this code: keep the slot and show the code itself, so
      // the row never shifts.
      return SizedBox(
        width: width,
        height: height,
        child: Center(
          child: FittedBox(
            child: Text(
              code.toUpperCase(),
              style: StyleText.fontSize12Weight500
                  .copyWith(color: AppColors.secondaryText),
            ),
          ),
        ),
      );
    }
    return ClipRRect(
      borderRadius: BorderRadius.circular(borderRadius),
      child: SvgPicture.asset(
        'assets/flags_svg/$code.svg',
        width: width,
        height: height,
        fit: BoxFit.cover,
      ),
    );
  }
}
