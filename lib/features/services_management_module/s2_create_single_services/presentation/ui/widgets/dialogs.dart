    barrierDismissible: true,
    builder: (dialogContext) {
      Future.delayed(Duration(seconds: 2), () {
        if (!navigated) {
          navigated = true;
          Navigator.of(dialogContext).pop();
          navigateAndFinish(rootContext, LayoutScreenServices());
        }
      });

      return WillPopScope(
        onWillPop: () async {
          if (!navigated) {
            navigated = true;
            Navigator.of(dialogContext).pop();
            navigateAndFinish(rootContext, LayoutScreenServices());
          }
          return false;
        },
