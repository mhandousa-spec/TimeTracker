extension DateTimeExtension on DateTime {
  int get dayOfYear {
    int dayOfYear = 0;
    for (int month = 1; month < this.month; month++) {
      dayOfYear += DateUtils.getDaysInMonth(year, month);
    }
    dayOfYear += day;
    return dayOfYear;
  }
}

